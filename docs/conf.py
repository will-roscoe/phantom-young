# -- add preamble to mathjax & other math configs.
import re as _re
_PREAMBLE_FP = "/win/e/Notebooks/General Notes/preamble.md"
with open(_PREAMBLE_FP,"r") as f:
    pre_lines = f.readlines()
    pre = " ".join(pre_lines)

_macros = {}

for match in _re.compile(   # matches \(re)?newcommand{\<name>}([<nargs>])?{<def>}
        r"\\(?:re)?newcommand"
        r"\{\\(?P<name>.*?)\}"
        r"(?:\[(?P<nargs>\d+)\])?"
        r"\{(?P<def>.+?)\}\s*"
        ).finditer(pre):
    if match:
        print("found",match)
        mc = f"{'{'}{match.group("def")}{'}'}"
        _macros[match.group("name")] = (
            [mc,int(narg)] if (narg:=match.group("nargs")) 
            else mc)   
print(_macros)

latex_elements = {'preamble': pre}
mathjax3_config = {"tex":{"macros": _macros}}



